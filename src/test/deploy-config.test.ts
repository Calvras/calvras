import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

const root = process.cwd();
const read = <T>(file: string): T => JSON.parse(readFileSync(path.resolve(root, file), "utf8")) as T;

type DeployConfig = {
  main: string;
  assets: { directory: string };
  no_bundle: boolean;
  compatibility_flags: string[];
  name: string;
  account_id: string;
  routes: { pattern: string; custom_domain: boolean }[];
  build?: { command?: string };
  vars?: Record<string, unknown>;
  d1_databases?: { binding: string; database_name: string; database_id: string; migrations_dir: string }[];
};

/**
 * The hosted build runs a bare `npx wrangler deploy` from the repository root. With no config there
 * wrangler tries to inject its own Vite plugin instead, which fails on the @lovable.dev/vite-tanstack-config
 * wrapper — so this root file is what keeps the deploy command alive.
 */
describe("the hosted deploy config", () => {
  const config = read<DeployConfig>("wrangler.json");

  it("points at the built output from the repository root", () => {
    expect(config.main).toBe(".output/server/index.mjs");
    expect(config.assets.directory).toBe(".output/public");
    expect(config.no_bundle).toBe(true);
    expect(config.compatibility_flags).toContain("nodejs_compat");
  });

  it("names the worker and the domain it serves", () => {
    expect(config.name).toBe("calvras");
    expect(config.account_id).toBe("6731a2cf3ac3e76d3f399f505a7e5c11");
    expect(config.routes).toEqual([{ pattern: "calvras.com", custom_domain: true }]);
  });

  it("builds the output it uploads, because Cloudflare's git build has no build step", () => {
    expect(config.build?.command).toBe("npm run build");
  });

  it("is regenerated by the build that produces the output", () => {
    const scripts = read<{ scripts: Record<string, string> }>("package.json").scripts;
    expect(scripts["build"]).toContain("node scripts/write-root-wrangler.mjs");
    expect(scripts["deploy"]).toBe("npm run build && npx wrangler deploy");
  });

  /**
   * The account ledger lives in a D1 database, and the Worker only sees it when the generated config
   * carries the binding. `d1.json` is gitignored, so the binding has to survive in the committed
   * wrangler.json too: reading it from the local file alone meant every hosted deploy uploaded a
   * Worker that promised a ledger it could not reach, and the owner console answered 503 forever.
   */
  it("binds the ledger on every build, not only on the machine that created the database", () => {
    const writer = readFileSync(path.resolve(root, "scripts/write-root-wrangler.mjs"), "utf8");
    expect(writer).toMatch(/d1\.json/);
    expect(writer).toMatch(/binding: "CALVRAS_DB"/);
    expect(writer).toMatch(/migrations_dir: "migrations"/);
    expect(existsSync(path.resolve(root, "migrations/0001_ledger.sql"))).toBe(true);
    expect(config.d1_databases).toEqual([{ binding: "CALVRAS_DB", database_name: "calvras-ledger", database_id: expect.stringMatching(/^[0-9a-f-]{16,64}$/), migrations_dir: "migrations" }]);
  });

  /** The console's analyst model is a plain config var, so the hosted build has to regenerate it too —
   * a name that only ever existed on one machine would leave the live report writing itself from
   * numbers with no explanation to anybody but the person who deployed. */
  it("carries the console's analyst model in the generated config", () => {
    const writer = readFileSync(path.resolve(root, "scripts/write-root-wrangler.mjs"), "utf8");
    expect(writer).toMatch(/CALVRAS_AI_MODEL/);
    expect(String(config.vars?.["CALVRAS_AI_MODEL"] || "")).toMatch(/:free$/);
  });
});

/** The browser tool must stay out of the hosted bundle: it is what dragged playwright and electron in. */
describe("the server bundle stays free of the desktop browser", () => {
  const source = readFileSync(path.resolve(root, "src/lib/runtime/browser-tools.ts"), "utf8");

  it("loads playwright only when a browser tool runs", () => {
    expect(source).not.toMatch(/^import \{[^}]*chromium[^}]*\} from ['"]playwright['"]/m);
    expect(source).toMatch(/@vite-ignore/);
  });

  it("ships playwright beside the desktop server", () => {
    const prep = readFileSync(path.resolve(root, "scripts/prepare-electron-runtime.mjs"), "utf8");
    expect(prep).toMatch(/"typescript", "playwright", "playwright-core"/);
  });

  it("does not resolve the compiler while the server module loads", () => {
    const intelligence = readFileSync(path.resolve(root, "src/lib/runtime/code-intelligence.ts"), "utf8");
    expect(intelligence).toMatch(/const ts = new Proxy/);
    expect(intelligence).not.toMatch(/^const ts: typeof TypeScript = runtimeRequire\("typescript"\);$/m);
  });
});
