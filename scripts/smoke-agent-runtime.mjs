const session = await (await post("session", { projectPath: root, mode: "ask" })).json(); assert.equal(session.ok, true);
async function tool(action, approvalToken) {
  const response = await post("tools", { sessionId: session.id, action, approvalToken });
  const events = (await response.text()).split("\n\n").filter(Boolean).map((event) => JSON.parse(event.slice(6)));
  return events.at(-1);
}
const write = { type: "write_file", path: "app.ts", content: "export const count: number = 2;\n" };
